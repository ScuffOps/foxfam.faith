export function getDailyCommunityWord(seedKey = getLocalDateKey()) {
  const index = hashSeed(seedKey) % COMMUNITY_WORDLE_SOLUTIONS.length;
  return COMMUNITY_WORDLE_SOLUTIONS[index];
}

export function getLocalDateKey(now = Date.now()) {
  const date = new Date(now);
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function hashSeed(seedKey) {
  return Array.from(String(seedKey)).reduce((hash, character) => {
    return (hash * 31 + character.charCodeAt(0)) >>> 0;
  }, 2166136261);
}
